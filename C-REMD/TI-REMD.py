def get_last_line(file_path):
    with open(file_path, 'r') as f:
        lines = f.read().splitlines()
        return lines[-1] if lines else None 

def incar_read():
    att,var = [],[]
    with open (dirpath('INCAR'),'r') as f:
        for line in f:
            temp = line.split('#',1)[0].strip()
            if not temp:
                continue
            temp2 = temp.split('=',1)
            att.append(temp2[0].replace(' ',''))
            var.append(temp2[1].replace(' ',''))
    incar = dict(zip(att,var))
    if incar.get('IBRION', 2) != '0':
        print(' ERROR, NOT MD INCAR')
        exit()    
    return incar

