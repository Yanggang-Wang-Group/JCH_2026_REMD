def job_sub(workdir,jname,index):
    qsub = subprocess.run(
        'qsub -N MD_J%s%.2d vasp.sh'%(jname,index),
        shell=True,cwd = workdir,capture_output=True,text=True
    )
    return_id = qsub.stdout
    return_id = return_id.replace('\n','')
    return return_id

def qsub_finish_check(job_id):
    i = 0
    while i < len(job_id):
        check = subprocess.run('qstat %s'%job_id[i],shell=True,capture_output=True)
        temp = check.stderr.decode()
        #statues = temp[2].split()
        if 'finished' in temp:
            print('Job %s finished.'%job_id[i])
            job_id.pop(i)
            i -= 1
        i += 1
    return job_id

