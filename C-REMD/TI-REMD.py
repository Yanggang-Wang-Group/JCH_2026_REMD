def init_pre(incar):
    cv = readcv(incar)
    job_id = []
    for i in range(cv.shape[0]):
        workdir = dirpath('%.3d/%.2d_%.2d'%(cv[i]*100,i,0))
        os.makedirs(workdir,exist_ok=True)
        incar['NSW'] = incar['RENSWINIT']
        with open (os.path.join(workdir,'INCAR'),'a+') as f:
            f.write('''# INCAR GENERATED BY TI-REMD@JIANGCH V2025.12
# CITE: 
''')
            for j in incar:
                if j[0:2] == 'RE':
                    continue
                else:
                    f.write('%s = %s\n'%(j,incar[j]))
        cmd = 'cp %s %s'%(dirpath('KPOINTS'),os.path.join(workdir,'KPOINTS'))
        os.system(cmd)
        cmd = 'cp %s %s'%(dirpath('POTCAR'),os.path.join(workdir,'POTCAR'))
        os.system(cmd)
        os.system('cp %s %s'%(dirpath('ICONST'),os.path.join(workdir,'ICONST')))
        indexa,indexb = ICONST_READ()
        try:
            cv_init = float(incar['RECVINIT'])
            cv_incream = float(incar['REINCREM'])
            xdatcar = ase.io.read(dirpath(incar['REINIT']),index=':')
            cv_array = np.linspace(cv_init,cv_init + cv_incream*(len(xdatcar)-1),len(xdatcar))
            cv_array -= cv[i]
            cv_array = np.abs(cv_array)
            xdat_index = np.where(cv_array == np.min(cv_array))[0][0]
            poscar = xdatcar[xdat_index]
        except:
            poscar = ase.io.read((dirpath('POSCAR')))
        coora = poscar.get_positions()[indexa-1]
        coorb = poscar.get_positions()[indexb-1]
        vector = coorb - coora
        length = np.linalg.norm(vector)
        unit_vector = vector / length
        new_coorb = coora + unit_vector * cv[i]
        poscar.positions[indexb-1] = new_coorb
        ase.io.write(os.path.join(workdir,'POSCAR'),poscar)          
        cmd = 'cp %s %s'%(dirpath(incar['REQSUB']),os.path.join(workdir,'vasp.sh'))
        os.system(cmd)
        job_id.append(job_sub(workdir,'01',i))
    log(1,'[Init REMD Job submitted]%s'%job_id)
    return 1


