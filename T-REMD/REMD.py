def REMD_pre():
    line = get_last_line(dirpath('REMD.log'))
    task = re.findall(r"\[\s*(\d+)\s*,\s*(\d+)\s*\]",line)
    task = [[int(x),int(y)] for x,y in task]
    jname = int((int(re.findall(r"\[J-(\d{3})-\]",line)[0]) / 10)) + 1
    job_id = []
    taskdir = find_last_dir()
    taskdirtmp = [k[-5:-3] for k in taskdir]    
    for i in range(len(task)):
        workdir = os.path.join(dirpath('%s'%task[i][0]),'%.2d_%.2d'%(task[i][1],jname))
        os.makedirs(workdir,exist_ok=True)
        #----- KPOINTS -----
        os.system('cp %s %s'%(dirpath('KPOINTS'),os.path.join(workdir,'KPOINTS')))
        os.system('cp %s %s'%(dirpath('ICONST'),os.path.join(workdir,'ICONST')))

        #----- POTCAR -----
        os.system('cp %s %s'%(dirpath('POTCAR'),os.path.join(workdir,'POTCAR'))) 
        #----- INCAR -----
        incar['NSW'] = incar['RENSWRUN']
        incar['TEBEG'] = str(task[i][0])
        incar['TEEND'] = str(task[i][0])
        with open (os.path.join(workdir,'INCAR'),'a+') as f:
            f.write('''# INCAR GENERATED BY REMD@JIANGCH V2025.03
# CITE: 
''')
            for j in incar:
                if j[0:2] == 'RE':
                    continue
                else:
                    f.write('%s = %s\n'%(j,incar[j]))
        #----- vasp.sh -----
        os.system('cp %s %s'%(dirpath(incar['REQSUB']),os.path.join(workdir,'vasp.sh')))
        #----- POSCAR -----               
        if jname == 1:
            os.system('cp %s %s'%(dirpath('POSCAR'),os.path.join(workdir,'POSCAR')))
        else:
            contcar = taskdir[taskdirtmp.index('%.2d'%(task[i][1]))]
            os.system('cp %s %s'%(os.path.join(dirpath(contcar),'CONTCAR'),
                                  os.path.join(workdir,'POSCAR')))
        job_id.append(job_sub(workdir,'%.2d'%(jname*10+1),i))
    jname = jname *10 +1
    log(jname,'[REMD Job submitted]%s'%job_id)
    return jname

def find_last_dir():
    taskdir = []
    for tmp in os.listdir(dirpath('')):
        if os.path.isdir(dirpath(tmp)) and tmp.isdigit():
            taskdirtmp,taskindex = [],[]
            for rep in os.listdir(dirpath(tmp)):
                if os.path.isdir(dirpath(os.path.join(tmp,rep))):
                    taskdirtmp.append(rep)
                    taskindex.append(int(rep[-2:]))
            taskdir.append(os.path.join(tmp,taskdirtmp[taskindex.index(max(taskindex))]))
    return taskdir
                 
def rep_exchange():
    line = get_last_line(dirpath('REMD.log'))
    jname = int(re.findall(r"\[J-(\d{3})-\]",line)[0])
  
    taskdir = find_last_dir()
    tmp = []
    i = 0
    while i < len(taskdir) - 1:
        dir1 = dirpath(taskdir[i])
        dir2 = dirpath(taskdir[i+1])
        print(dir2)
        tail1 = subprocess.run('tail -1 OSZICAR',shell=True,cwd = dir1,capture_output=True,text=True)
        tail = tail1.stdout.split()
        tmp1 = float(tail[2])
        ene1 = float(tail[8])
        tail2 = subprocess.run('tail -1 OSZICAR',shell=True,cwd = dir2,capture_output=True,text=True)
        tail = tail2.stdout.split()
        tmp2 = float(tail[2])
        ene2 = float(tail[8])
        kb = 1.380649E-23
        p = (1/(kb*tmp1)-1/(kb*tmp2))*(ene1-ene2)*1.6022E-19
        p = math.exp(p)
        if p > 1: p = 1
        rand = random.random()
        if rand <= p:
            tmp.append([int(taskdir[i][:3]),int(taskdir[i+1][-5:-3])])
            tmp.append([int(taskdir[i+1][:3]),int(taskdir[i][-5:-3])])
            i += 1
        else:
            tmp.append([int(taskdir[i][:3]),int(taskdir[i][-5:-3])])
        i += 1
    if len(tmp) < len(taskdir):
        tmp.append([int(taskdir[len(taskdir)-1][:3]),int(taskdir[len(taskdir)-1][-5:-3])])
    jname += 1
    log(jname,'[replica exchange finished]%s'%tmp)            
    return jname
    
