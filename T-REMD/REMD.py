def dirpath(a):
    return os.path.join(os.path.dirname(__file__),a)

def log(jname,a):
    with open(dirpath('REMD.log'),'a+') as loger:
        now = datetime.datetime.now()
        format_time = now.strftime("%Y.%m.%d.%H:%M:%S")
        loger.write('[%s][J-%.3d-]%s\n'%(format_time,jname,a))
        print('[%s][J-%.3d-]:%s'%(format_time,jname,a))
    return

def get_last_line(file_path):
    with open(file_path, 'r') as f:
        lines = f.read().splitlines()
        return lines[-1] if lines else None 

def incar_read():
    att,var = [],[]
    with open (dirpath('INCAR'),'r') as f:
        for line in f:
            temp = line.split('#',1)[0].strip()
            if not temp:
                continue
            temp2 = temp.split('=',1)
            att.append(temp2[0].replace(' ',''))
            if temp2[0].replace(' ','') == 'POMASS':
                var.append(temp2[1].replace(' ',' '))
            else:
                var.append(temp2[1].replace(' ',''))
    incar = dict(zip(att,var))
    if incar.get('IBRION', 2) != '0':
        print(' ERROR, NOT MD INCAR')
        exit()    
    return incar

def job_sub(workdir,jname,index):
    qsub = subprocess.run(
        'qsub -N MD_J%s%.2d vasp.sh'%(jname,index),
        shell=True,cwd = workdir,capture_output=True,text=True
    )
    return_id = qsub.stdout
    return_id = return_id.replace('\n','')
    return return_id

def qsub_finish_check(job_id):
    i = 0
    while i < len(job_id):
        check = subprocess.run('qstat %s'%job_id[i],shell=True,capture_output=True)
        temp = check.stderr.decode()
        #statues = temp[2].split()
        if 'finished' in temp:
            print('Job %s finished.'%job_id[i])
            job_id.pop(i)
            i -= 1
        i += 1
    return job_id

def vasp_finish_check():
    print('Waiting for job running.')
    line = get_last_line(dirpath('REMD.log'))    
    jname = int(re.findall(r"\[J-(\d{3})-\]",line)[0])
    job_id = re.findall(r"(\d+\.mgr)",line)
    a = 0
    while a == 0:
        job_id = qsub_finish_check(job_id)
        if len(job_id) > 0:
            time.sleep(30)
        else:
            return jname + 1 

